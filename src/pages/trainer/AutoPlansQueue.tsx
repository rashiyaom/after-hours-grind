import { useMemo, useState } from "react";
import { motion } from "framer-motion";
import { CheckCircle2, XCircle, Pencil, Clock3, ArrowLeft } from "lucide-react";
import { toast } from "sonner";
import { useStore, useAppStore, useCurrentUser } from "@/hooks/useStore";
import { LUXURY_EASE } from "@/lib/motionTokens";
import { Student, Trainer } from "@/types";
import { useNavigate } from "react-router-dom";

export default function AutoPlansQueuePage() {
  const navigate = useNavigate();
  const currentUser = useCurrentUser();
  const { autoGeneratedPlansQueue, reviewAutoGeneratedPlan, editAutoGeneratedPlanDay } = useStore();
  const users = useAppStore((s) => s.users);
  const [feedback, setFeedback] = useState<Record<string, string>>({});

  const trainer = currentUser?.role === "trainer" ? (currentUser as Trainer) : null;

  // Get IDs of plans belonging to trainer's assigned students only
  // Get IDs of plans belonging to trainer's assigned students OR unassigned students
  const visiblePlanIds = useMemo(() => {
    const ids = new Set<string>();
    Object.values(users).forEach((u) => {
      if (u.role !== "student") return;
      const s = u as Student;
      if (s.trainerId === trainer?.id && s.currentPlanId) {
        ids.add(s.currentPlanId);
      }
    });
    return ids;
  }, [users, trainer?.id]);

  const queue = useMemo(
    () => autoGeneratedPlansQueue.filter((plan) => {
      if (plan.status !== "pending_trainer_approval") return false;
      // Trainer sees plans from their students and unassigned students; admin can see all
      if (trainer && !visiblePlanIds.has(plan.id)) return false;
      return true;
    }),
    [autoGeneratedPlansQueue, trainer, visiblePlanIds]
  );

  const approve = (planId: string) => {
    reviewAutoGeneratedPlan(planId, "approve");
    toast.success("Plan approved and moved to active.");
  };

  const reject = (planId: string) => {
    const note = feedback[planId]?.trim();
    if (!note) {
      toast.error("Feedback is required to reject a plan.");
      return;
    }
    reviewAutoGeneratedPlan(planId, "reject", note);
    toast.warning("Plan rejected with trainer feedback.");
  };

  const quickEdit = (planId: string) => {
    editAutoGeneratedPlanDay(planId, 1, 1, {
      tasks: [
        {
          type: "workout",
          title: "Trainer Edited: Technique + Mobility Primer",
          durationMinutes: 25,
          intensity: "low",
          points: 40,
        },
        {
          type: "nutrition",
          title: "Trainer Edited: High-protein breakfast anchor",
          points: 30,
        },
        {
          type: "habit",
          title: "Trainer Edited: 8k steps + sleep tracker",
          points: 30,
        },
      ],
    });
    toast.success("Week 1 Day 1 updated by trainer.");
  };

  return (
    <div className="relative overflow-hidden p-6 sm:p-8 lg:p-10">
      <div className="pointer-events-none absolute inset-0">
        <div className="absolute left-0 top-0 h-56 w-56 rounded-full bg-primary/10 blur-3xl" />
        <div className="absolute bottom-0 right-0 h-56 w-56 rounded-full bg-emerald-500/10 blur-3xl" />
      </div>

      <div className="relative mx-auto max-w-6xl space-y-6">
        <div>
          <p className="inline-flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.22em] text-primary">
            <span className="h-2 w-2 animate-pulse rounded-full bg-primary" />
            Trainer Workbench
          </p>
          <h1 className="mt-2 font-display text-3xl font-semibold tracking-tight">Auto Generated Plans Queue</h1>
          <p className="mt-2 text-sm text-muted-foreground">Review AI-generated plans, edit tasks, then approve or reject with feedback.</p>
        </div>

        <div className="space-y-4">
          {queue.length === 0 ? (
            <div className="rounded-2xl border border-white/10 bg-card p-6 text-sm text-muted-foreground shadow-[0_12px_28px_rgba(20,20,20,0.22)]">
              No pending plans in queue.
            </div>
          ) : (
            queue.map((plan) => (
              <motion.div
                key={plan.id}
                initial={{ opacity: 0, y: 14 }}
                animate={{ opacity: 1, y: 0 }}
                whileHover={{ y: -2 }}
                transition={{
                  opacity: { duration: 0.52, ease: LUXURY_EASE },
                  y: { type: "spring", stiffness: 150, damping: 24, mass: 0.95 },
                }}
                className="rounded-2xl border border-white/10 bg-card/95 p-5 shadow-[0_12px_28px_rgba(20,20,20,0.2)]"
              >
                <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
                  <div>
                    <p className="text-sm font-semibold tracking-tight text-foreground">{plan.title}</p>
                    <p className="mt-1 text-xs text-muted-foreground">Goal: {plan.basedOn?.goal} | Level: {plan.basedOn?.level} | BMI: {plan.basedOn?.bmi}</p>
                    <div className="mt-2 inline-flex items-center gap-2 rounded-full border border-amber-500/35 bg-amber-500/10 px-3 py-1 text-xs text-amber-300">
                      <Clock3 className="h-3.5 w-3.5" /> pending_trainer_approval
                    </div>
                  </div>

                  <div className="flex flex-wrap gap-2">
                    <button onClick={() => quickEdit(plan.id)} className="inline-flex items-center gap-1 rounded-full border border-white/15 px-3 py-2 text-xs font-semibold transition-all hover:-translate-y-0.5 hover:border-white/30 hover:bg-white/5">
                      <Pencil className="h-3.5 w-3.5" /> Edit Day
                    </button>
                    <button onClick={() => approve(plan.id)} className="inline-flex items-center gap-1 rounded-full bg-emerald-500/90 px-3 py-2 text-xs font-semibold text-black transition-all hover:-translate-y-0.5 hover:shadow-[0_8px_20px_rgba(16,185,129,0.35)]">
                      <CheckCircle2 className="h-3.5 w-3.5" /> Approve
                    </button>
                    <button onClick={() => reject(plan.id)} className="inline-flex items-center gap-1 rounded-full bg-rose-500/90 px-3 py-2 text-xs font-semibold text-black transition-all hover:-translate-y-0.5 hover:shadow-[0_8px_20px_rgba(244,63,94,0.35)]">
                      <XCircle className="h-3.5 w-3.5" /> Reject
                    </button>
                  </div>
                </div>

                <textarea
                  value={feedback[plan.id] ?? ""}
                  onChange={(event) => setFeedback((prev) => ({ ...prev, [plan.id]: event.target.value }))}
                  placeholder="Trainer feedback (required for rejection)"
                  className="mt-4 min-h-20 w-full rounded-xl border border-white/15 bg-background px-3 py-2 text-sm outline-none transition-all placeholder:text-muted-foreground/50 focus:border-primary/40 focus:shadow-[0_0_0_3px_rgba(245,158,11,0.15)]"
                />

                {plan.generationIssues && plan.generationIssues.length > 0 && (
                  <div className="mt-3 rounded-xl border border-amber-500/30 bg-amber-500/10 p-3">
                    <p className="text-xs font-semibold uppercase tracking-[0.16em] text-amber-300">Risk flags</p>
                    <ul className="mt-2 space-y-1 text-xs text-amber-200/90">
                      {plan.generationIssues.slice(0, 3).map((issue) => (
                        <li key={`${plan.id}-${issue.code}-${issue.message}`}>{issue.message}</li>
                      ))}
                    </ul>
                  </div>
                )}

                {plan.weeks?.[0]?.days?.[0] && (
                  <div className="mt-3 rounded-xl border border-white/10 bg-background/40 p-3">
                    <p className="text-xs font-semibold uppercase tracking-[0.16em] text-muted-foreground">Week 1 Day 1 preview</p>
                    <ul className="mt-2 space-y-1 text-xs text-foreground/90">
                      {plan.weeks[0].days[0].tasks.map((task, idx) => (
                        <li key={`${plan.id}-${task.type}-${idx}`}>{task.type}: {task.title}</li>
                      ))}
                    </ul>
                  </div>
                )}
              </motion.div>
            ))
          )}
        </div>
      </div>
    </div>
  );
}
